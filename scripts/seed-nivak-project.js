function plainContent() {
  const featureLines = FEATURE_GROUPS.flatMap(g => [g.group, ...g.features.map(f => `${f.h}\n${f.t}`)]);
  return [
    'نیواک — اپلیکیشن هوشمند مدیریت پیامک',
    ...featureLines,
    ...HOW_IT_WORKS.map(s => `${s.h}\n${s.t}`),
  ].join('\n\n');
}

async function run() {
  console.log('🔌 در حال اتصال به دیتابیس...');
  await mongoose.connect(config.mongoUri);

  const existing = await Project.findOne({ title: post.title });
  if (existing) {
    const blocks = buildBlocks();
    await Project.findByIdAndUpdate(existing._id, {
      summary: post.summary,
      content: plainContent(),
      blocks,
      metaDescription: post.summary,
    });
    console.log(`✅ پروژه‌ی «نیواک» با محتوای جدید به‌روزرسانی شد → /projects/${existing.slug}`);
    console.log('   (اسلاگ، لینک، و تصاویری که قبلاً ست کرده بودی دست‌نخورده موندن.)');
  } else {
    const blocks = buildBlocks();
    const doc = await Project.create({
      title: post.title,
      summary: post.summary,
      content: plainContent(),
      blocks,
      tag: post.tag,
      coverImage: '',
      link: post.link,
      metaTitle: 'نیواک | اپلیکیشن مدیریت هوشمند پیامک با هوش مصنوعی',
      metaDescription: post.summary,
      focusKeyword: 'اپلیکیشن مدیریت پیامک نیواک',
      published: true,
    });
    console.log(`✅ پروژه‌ی «نیواک» ساخته شد → /projects/${doc.slug}`);
  }

  await mongoose.disconnect();
  process.exit(0);
}

run().catch(err => { console.error('❌ خطا:', err); process.exit(1); });
