// چند شکل مختلف اشاره به برند و کارهامون — تا متن‌ها تکراری و ماشینی به‌نظر نرسن
const BRAND_MENTIONS = [SITE, `تیم ${SITE}`, `آژانس دیجیتال ${SITE}`, `کارشناسان ${SITE}`, `متخصصان ما`];
function brand(i) { return BRAND_MENTIONS[i % BRAND_MENTIONS.length]; }

let _uid = 0;
function block(type, data) {
  _uid++;
  return { id: `seed_${Date.now()}_${_uid}`, type, data };
}

// از یک ساختار ساده (تیتر معرفی + بخش‌ها + لیست + تصویر + دکمه) یک آرایه‌ی بلوک کامل می‌سازه
function buildBlocks(post) {
  const blocks = [];
  blocks.push(block('paragraph', { text: post.intro }));

  post.sections.forEach((sec) => {
    blocks.push(block('heading', { text: sec.heading, level: 3 }));
    blocks.push(block('paragraph', { text: sec.text }));
    if (sec.list) {
      blocks.push(block('list', { items: sec.list, ordered: false }));
    }
  });

  if (post.image) {
    blocks.push(block('image', { url: '', caption: `📌 پیشنهاد تصویر: ${post.image}` }));
  }

  if (post.quote) {
    blocks.push(block('quote', { text: post.quote, author: brand(post.idx + 2) }));
  }

  blocks.push(block('paragraph', { text: post.closing }));
  blocks.push(block('button', { text: post.cta.text, url: post.cta.url }));

  return blocks;
}

function plainContent(post) {
  return [post.intro, ...post.sections.map(s => `${s.heading}\n${s.text}`), post.closing].join('\n\n');
}

