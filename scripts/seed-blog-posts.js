async function run() {
  console.log('🔌 در حال اتصال به دیتابیس...');
  await mongoose.connect(config.mongoUri);
  console.log('✅ اتصال برقرار شد.\n');

  let created = 0, skipped = 0;
  const imageReminders = [];

  for (let i = 0; i < POSTS.length; i++) {
    const p = { ...POSTS[i], idx: i };

    const exists = await Blog.findOne({ title: p.title });
    if (exists) {
      console.log(`⏭️  رد شد (از قبل وجود دارد): ${p.title}`);
      skipped++;
      continue;
    }

    // مطمئن می‌شویم دسته‌بندی هم در لیست دسته‌بندی‌ها ثبت باشد
    await Category.findOneAndUpdate({ name: p.tag }, { name: p.tag }, { upsert: true });

    const blocks = buildBlocks(p);
    const doc = await Blog.create({
      title: p.title,
      content: plainContent(p),
      blocks,
      tag: p.tag,
      coverImage: '',
      metaTitle: p.title,
      metaDescription: p.metaDescription,
      focusKeyword: p.focusKeyword,
      published: true,
    });

    console.log(`✅ ساخته شد: ${p.title}`);
    imageReminders.push({ title: p.title, id: doc._id.toString(), image: p.image });
    created++;
  }

  console.log(`\n🎉 تمام شد — ${created} پست جدید ساخته شد، ${skipped} پست تکراری رد شد.\n`);

  if (imageReminders.length) {
    console.log('📸 یادآوری تصاویر — این پست‌ها منتظر آپلود تصویر واقعی هستن:\n');
    imageReminders.forEach((r, i) => {
      console.log(`${i + 1}. ${r.title}`);
      console.log(`   لینک ویرایش: /admin/blog  (پیشنهاد تصویر: ${r.image})`);
    });
    console.log('\nبرای هرکدوم: وارد /admin/blog بشو → پست رو باز کن → روی بلوک تصویر بزن → از «📁 کتابخانه» یک عکس مرتبط آپلود کن.');
  }

  await mongoose.disconnect();
  process.exit(0);
}

run().catch(err => {
  console.error('❌ خطا:', err);
  process.exit(1);
});
