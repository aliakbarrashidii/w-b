
// تبدیل عنوان به یک اسلاگ تمیز و مناسب URL — حروف فارسی/عربی رو نگه می‌داره
// (چون در سئوی فارسی، لینک‌های فارسی خوانا و معتبر و حتی مفیدند)، فقط
// علائم نگارشی و فاصله‌های اضافی رو پاک می‌کنه.
function slugify(text) {
  return String(text)
    .trim()
    .replace(/[؟!.,:;«»"'()\[\]{}،٬]/g, '') // حذف علائم نگارشی رایج فارسی/انگلیسی
    .replace(/[\u200c\s]+/g, '-') // فاصله و نیم‌فاصله -> خط تیره
    .replace(/-+/g, '-') // چند خط‌تیره‌ی پیاپی -> یکی
    .replace(/^-+|-+$/g, ''); // حذف خط‌تیره‌ی ابتدا/انتهای رشته
}

module.exports = slugify;
